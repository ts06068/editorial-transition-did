def write_results_readme(paths: AnalysisPaths) -> None:
    """Write methodological notes alongside the generated results."""
    # This output-level README records analysis choices; it is separate from repository setup docs.
    text = (
        "# Editorial board natural-experiment analysis results\n\n"
        f"Analysis cutoff: {ANALYSIS_CUTOFF:%Y-%m-%d}\n\n"
        f"Primary intervention definition: {PRIMARY_WINDOW.post_start:%Y-%m-%d}\n\n"
        f"Primary pre period: {PRIMARY_WINDOW.pre_start:%Y-%m-%d} to "
        f"{PRIMARY_WINDOW.pre_end:%Y-%m-%d}\n\n"
        f"Primary post period: {PRIMARY_WINDOW.post_start:%Y-%m-%d} to "
        f"{PRIMARY_WINDOW.post_end:%Y-%m-%d}\n\n"
        "Journals: CIRC, EHJ, and JACC. JAMA Cardiology is excluded throughout.\n\n"
        "Observed 1-year citation counts require complete 12-month follow-up. Incomplete 1-year "
        "outcomes are stored as missing and are never treated as low citation counts. Table 2 "
        "separately reports total cumulative citations at the analysis cutoff for the June "
        "2025-June 2026 cohort and labels them as such.\n\n"
        "The primary effect is a raw four-mean DiD: the JACC post-minus-pre change minus the "
        "equally weighted mean of the corresponding CIRC and EHJ changes. Confidence intervals "
        "use publication-month block bootstrap with each publication month resampled jointly "
        "across journals. June and August 2024 are alternative intervention definitions; August "
        "uses 11 complete months per period because July 2025 has incomplete 12-month follow-up "
        "at the analysis cutoff. Prediction uses rolling temporal validation, a 2022-06 to "
        "2024-05 temporal holdout, and final refitting through 2024-05 publications.\n\n"
        "Main tables and figures are in `main_tables` and `main_figures`. Word tables are rendered "
        "directly from analysis data in the manuscript format rather than copied from Excel. "
        "Individual files are accompanied by `Main_Tables.docx`, `Supplementary_Tables.docx`, "
        "and the combined `CLEAR_CARD_editorial_analysis_tables.docx`. Detailed monthly, "
        "quarterly, robustness, model-fold, and article-level forecast outputs are in the "
        "supplementary folders and cache.\n"
    )
    # Write beside the tables and figures so exported result bundles remain self-describing.
    (paths.output_dir / "README.md").write_text(text, encoding="utf-8")
